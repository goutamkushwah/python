a = True
b = False
print("a and b:", a and b)   # False
print("a or b:", a or b)     # True
print("not a:", not a)       # False
print("not b:", not b)       # True
# With numbers
x = 10
y = 20
print("x > 5 and y > 15:", x > 5 and y > 15)   # True
print("x > 15 or y > 15:", x > 15 or y > 15)   # True
print("not(x > 5):", not(x > 5))               # False
