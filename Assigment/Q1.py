# Integer
num = 10
print("Integer:", num, type(num))

# Float
pi = 3.14
print("Float:", pi, type(pi))

# Complex
comp = 2 + 3j
print("Complex:", comp, type(comp))

# String
name = "Python"
print("String:", name, type(name))

# Boolean
is_valid = True
print("Boolean:", is_valid, type(is_valid))

# List
fruits = ["apple", "banana", "mango"]
print("List:", fruits, type(fruits))

# Tuple
colors = ("red", "green", "blue")
print("Tuple:", colors, type(colors))

# Set
unique_numbers = {1, 2, 3, 4}
print("Set:", unique_numbers, type(unique_numbers))

# Dictionary
person = {"name": "Goutam", "age": 25}
print("Dictionary:", person, type(person))

# NoneType
nothing = None
print("NoneType:", nothing, type(nothing))
