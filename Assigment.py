# Simple assignment
x = 10
print("Initial value of x:", x)

# Using += (add and assign)
x += 5   # same as x = x + 5
print("After x += 5:", x)

# Using -= (subtract and assign)
x -= 3   # same as x = x - 3
print("After x -= 3:", x)

# Using *= (multiply and assign)
x *= 2   # same as x = x * 2
print("After x *= 2:", x)

# Using //= (integer divide and assign)
x //= 4   # keeps integer instead of float
print("After x //= 4:", x)

# Using //= (floor division and assign)
x //= 2  
print("After x //= 2:", x)

# Using %= (modulus and assign)
x %= 3
print("After x %= 3:", x)

# Using **= (exponent and assign)
x **= 2
print("After x **= 2:", x)

# Using &= (bitwise AND and assign)
x &= 2
print("After x &= 2:", x)

# Using |= (bitwise OR and assign)
x |= 1
print("After x |= 1:", x)

# Using ^= (bitwise XOR and assign)
x ^= 3
print("After x ^= 3:", x)

# Using <<= (left shift and assign)
x <<= 1 
print("After x <<= 1:", x)

# Using >>= (right shift and assign)
x >>= 1
print("After x >>= 1:", x)
